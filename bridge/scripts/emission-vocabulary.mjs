#!/usr/bin/env node
// Regenerate the drift detector's known agent vocabulary from the vendored emission
// inventories (protocol/openclaw/<version>/agent-emissions.json).
//
//   node scripts/emission-vocabulary.mjs            print the module it would write
//   node scripts/emission-vocabulary.mjs --write    write src/providers/openclaw/agent-emission-vocabulary.ts
//   node scripts/emission-vocabulary.mjs --check    exit 1 when that file is not what it would write
//
// The bridge runs from `dist/` in a container where `protocol/` is not on disk, so the
// sets are a LITERAL module rather than a runtime read of the inventory — the same reason
// KNOWN_AGENT_FIELDS is a literal. What keeps the literal honest is
// test/emission-vocabulary.test.ts, which recomputes the sets and compares them element by
// element; this script only spares a human from typing them.
//
// UNION over every vendored inventory: a stream, phase or key that a supported gateway
// emits is not drift, whichever version emits it (the KNOWN_AGENT_FIELDS rule).

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

import { compareVersions, parseVersion } from "../src/compat.ts";
import { runtimeVocabulary } from "./lib/emission-vocabulary.mjs";

const BRIDGE = path.resolve(import.meta.dirname, "..");
const PROTOCOL = path.join(BRIDGE, "protocol", "openclaw");
export const MODULE_PATH = path.join(BRIDGE, "src", "providers", "openclaw", "agent-emission-vocabulary.ts");

/** Versions holding an emission inventory, oldest first by version. */
export function inventoryVersions() {
  return fs
    .readdirSync(PROTOCOL, { withFileTypes: true })
    .filter((e) => e.isDirectory() && parseVersion(e.name) !== null)
    .map((e) => e.name)
    .filter((v) => fs.existsSync(path.join(PROTOCOL, v, "agent-emissions.json")))
    .sort((a, b) => compareVersions(parseVersion(a), parseVersion(b)));
}

const wrap = (items, indent) => {
  const lines = [];
  let line = "";
  for (const s of items.map((x) => JSON.stringify(x))) {
    if (line && line.length + s.length + 2 > 92 - indent.length) {
      lines.push(`${indent}${line.trimEnd()}`);
      line = "";
    }
    line += `${s}, `;
  }
  if (line) lines.push(`${indent}${line.trimEnd()}`);
  return lines.join("\n");
};

const setLiteral = (items, indent) =>
  items.length === 0 ? "new Set<string>()" : `new Set([\n${wrap(items, `${indent}  `)}\n${indent}])`;

const recordLiteral = (rec) =>
  `{\n${Object.entries(rec)
    .map(([k, items]) => `  ${JSON.stringify(k)}: ${setLiteral(items, "  ")},`)
    .join("\n")}\n}`;

export function renderModule(versions, vocab) {
  return `// GENERATED by scripts/emission-vocabulary.mjs from the vendored emission inventories
// (protocol/openclaw/<version>/agent-emissions.json): ${versions.join(", ")}.
// Do not edit by hand — re-run \`node scripts/emission-vocabulary.mjs --write\`.
// test/emission-vocabulary.test.ts recomputes every set and compares it element by element.
//
// The protocol drift detector (protocol-drift.ts) judges each inbound \`agent\` frame
// against these, PER STREAM: a stream, a phase or a \`data\` key absent from them is one
// the vendored upstream never emits there — counted by digest, or by name when the name is
// the inventory's own, never with content. The union over the inventories is the rule
// KNOWN_AGENT_FIELDS follows: what a supported gateway emits is not drift.

/** The versions whose inventories these sets are the union of. */
export const AGENT_EMISSION_VOCABULARY_VERSIONS: readonly string[] = ${JSON.stringify(versions)};

/** Every literal \`stream\` the inventories name (dotted plugin-scoped ones included). */
export const KNOWN_AGENT_STREAMS: ReadonlySet<string> = ${setLiteral(vocab.streams, "")};

/** Per stream, the literal \`data.phase\` values its emitters write. */
export const KNOWN_AGENT_PHASES_BY_STREAM: Readonly<Record<string, ReadonlySet<string>>> = ${recordLiteral(vocab.phasesByStream)};

/** Per stream, every \`data\` key its emitters (and the gateway's own rewrites) write. */
export const KNOWN_AGENT_DATA_KEYS_BY_STREAM: Readonly<Record<string, ReadonlySet<string>>> = ${recordLiteral(vocab.keysByStream)};

/** \`data\` keys of emitters whose stream the derivation could not resolve. Known on NO
 *  stream: an unresolved emitter COULD have added one, so the detector reports it apart
 *  (\`opaquekey_\`) instead of letting it pass on every stream. */
export const OPAQUE_EMITTER_AGENT_DATA_KEYS: ReadonlySet<string> = ${setLiteral(vocab.opaqueEmitterKeys, "")};

/** Chat \`message.content[].type\` values the gateway's display projection fabricates or
 *  recognizes, spelled exactly as its literals are. */
export const KNOWN_CHAT_CONTENT_PART_TYPES: ReadonlySet<string> = ${setLiteral(vocab.chatContentPartTypes, "")};

/** Literals the projection compares a block's type with after NORMALIZING it, per
 *  normalization chain (\`trim\`, \`lowercase\`, applied in order): a wire type is known
 *  when its normalized form is one of them (\`toolResult\` → \`toolresult\`). */
export const KNOWN_CHAT_CONTENT_PART_TYPES_FOLDED: Readonly<Record<string, ReadonlySet<string>>> = ${recordLiteral(vocab.chatContentPartFolds)};
`;
}

export function expectedModule() {
  const versions = inventoryVersions();
  if (versions.length === 0) throw new Error("no vendored emission inventory");
  const inventories = versions.map((v) =>
    JSON.parse(fs.readFileSync(path.join(PROTOCOL, v, "agent-emissions.json"), "utf8")),
  );
  return renderModule(versions, runtimeVocabulary(inventories));
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const text = expectedModule();
  if (process.argv.includes("--write")) {
    fs.writeFileSync(MODULE_PATH, text);
    console.error(`[emission-vocabulary] wrote ${path.relative(BRIDGE, MODULE_PATH)}`);
  } else if (process.argv.includes("--check")) {
    const current = fs.existsSync(MODULE_PATH) ? fs.readFileSync(MODULE_PATH, "utf8") : "";
    if (current !== text) {
      console.error(`[emission-vocabulary] ${path.relative(BRIDGE, MODULE_PATH)} is stale — re-run with --write`);
      process.exit(1);
    }
  } else {
    process.stdout.write(text);
  }
}
