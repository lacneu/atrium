#!/usr/bin/env node
// Regenerate the cross-repo CONTRACT FIXTURE from a live bridge (W11/G8).
//
//   node scripts/refresh-capabilities-fixture.mjs [--bridge http://127.0.0.1:8790]
//
// `src/chat/bridgeCapabilitiesFixture.ts` is the only thing that lets this repo notice a
// capability RENAME on the bridge side: the app and the bridge pin their own lists with
// their own tests, and two self-referential pins cannot see each other drift. The fixture
// is the anchor between them — and it was refreshed BY HAND, from a gateway two minor
// versions old (2026.5.19, captured 2026-06-12, while `maxValidated` is 2026.7.1). An
// anchor nobody re-captures anchors the past.
//
// This script captures it instead. It writes the module's DATA; the header comment above
// it explains why the fixture exists and is preserved verbatim.
//
// ANONYMISATION: `instanceName`, `key` and `agentId` are deployment identity, not
// contract — they are rewritten to stable placeholders. Everything else is the real
// response, capability records included, because the record IS the contract being pinned.
// The rewrite is explicit and narrow on purpose: the frame anonymiser next door is tuned
// for gateway frames, and bending it to a small structured body would trade a correct
// twenty lines for a subtle reuse.

import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import process from "node:process";

const REPO = path.resolve(new URL("..", import.meta.url).pathname);
const OUT = path.join(REPO, "src/chat/bridgeCapabilitiesFixture.ts");

/** Stable key order, so the comparison is about VALUES and never about property order. */
function replacerSorted(_key, value) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return value;
  return Object.fromEntries(Object.entries(value).sort(([a], [b]) => (a < b ? -1 : 1)));
}

function parseArgs(argv) {
  const args = { bridge: "http://127.0.0.1:8790" };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--bridge") args.bridge = argv[++i];
    else throw new Error(`unknown argument: ${argv[i]}`);
  }
  return args;
}

/** Deployment identity -> stable placeholders.
 *
 *  The OPENCLAW instance takes `main`: it is the one every test reads, and handing that
 *  name to whichever target happened to come first put it on the Hermes row — a fixture
 *  that reads backwards to anyone opening it. */
function anonymise(body, primaryInstance) {
  const instances = new Map();
  if (typeof primaryInstance === "string") instances.set(primaryInstance, "main");
  const instanceAlias = (name) => {
    if (typeof name !== "string") return name;
    if (!instances.has(name)) instances.set(name, `inst${instances.size + 1}`);
    return instances.get(name);
  };
  const agents = new Map();
  const agentAlias = (id) => {
    if (typeof id !== "string") return id;
    if (!agents.has(id)) agents.set(id, `agent${agents.size + 1}`);
    return agents.get(id);
  };
  const out = structuredClone(body);
  if (typeof out.instanceName === "string") out.instanceName = instanceAlias(out.instanceName);
  for (const target of out.targets ?? []) {
    target.instanceName = instanceAlias(target.instanceName);
    if ("agentId" in target) target.agentId = agentAlias(target.agentId);
    if ("key" in target) target.key = agentAlias(target.key);
  }
  return out;
}

/** The header is CONTRACT PROSE: it says why the fixture exists and how it is produced.
 *  Regenerating rewrites the data under it, never the explanation. */
function header(source, capturedAt) {
  return `// CONTRACT FIXTURE — captured VERBATIM from a LIVE bridge \`GET /capabilities\`.
//
// GENERATED by scripts/refresh-capabilities-fixture.mjs — do not edit by hand. Only
// runtime identifiers are anonymised (instanceName/key/agentId: deployment env, not
// contract); every other byte is the real response, including the per-target capability
// record the bridge RESOLVED for that gateway version.
//
// WHY IT EXISTS (red-team finding P2-1): the app and bridge repos ship on separate cycles
// and cannot import each other, so each pins its capability list with its own tests — two
// self-referential pins cannot detect drift BETWEEN the repos. This captured body is the
// cross-repo anchor: capabilities.test.ts asserts the UI's contract PARTITIONS this
// manifest exactly (consumed + declared-not-consumed = the manifest), and
// convex/compat.test.ts normalizes this exact body. A bridge-side rename therefore lands
// as a red test here instead of a silently hidden control.
//
// TO REFRESH: point a bridge at a validated gateway and run
//   node scripts/refresh-capabilities-fixture.mjs --bridge <url>
// The live bench does it as part of a validation run, so the anchor tracks the version
// the bench actually validated rather than whichever one somebody last pasted.
//
// Source: ${source} — captured ${capturedAt}
//
// Imported by TESTS ONLY (src + convex test suites) — never by app or deployed
// Convex code, so it adds zero runtime weight.
`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const url = `${args.bridge.replace(/\/$/, "")}/capabilities`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} answered HTTP ${res.status}`);
  const body = await res.json();

  // REFUSALS, so a fixture can never anchor less than it claims to.
  const manifest = body?.compat?.providers?.openclaw?.capabilities;
  if (manifest === undefined || Object.keys(manifest).length === 0) {
    throw new Error("the bridge reports no openclaw capability manifest");
  }
  const openclaw = (body.targets ?? []).find((t) => t?.provider === "openclaw");
  if (openclaw === undefined) {
    throw new Error("no openclaw target — point the bridge at a live gateway first");
  }
  if (typeof openclaw.gatewayVersion !== "string") {
    throw new Error(
      "the openclaw target has no resolved gatewayVersion — its capability record would " +
        "be the version-less subset, which anchors nothing",
    );
  }
  if (Object.keys(openclaw.capabilities ?? {}).length !== Object.keys(manifest).length) {
    throw new Error(
      "the resolved target record does not cover the manifest — capturing it would pin a " +
        "partial contract",
    );
  }

  // The bridge ANSWERING must serve the manifest THIS CHECKOUT compiles. A running
  // process keeps its old tables until restarted, so capturing from it writes an anchor
  // to the code as it USED to be — the exact defect this script exists to end. Caught the
  // first time it happened: a Hermes manifest correction sat in `src` while the captured
  // body still showed the old surface. Comparing versions would not have seen it (a
  // source edit does not bump `package.json`); comparing the TABLES does.
  // …and the compiled artifact must itself come from the CURRENT sources. Comparing the
  // served manifest against `dist` alone passes when BOTH are stale — an edit to
  // `src/compat.ts` with no rebuild leaves the old table on both sides and the check
  // agrees with itself (raised in review). Same freshness rule the promoter's fidelity
  // gate uses.
  const newest = (dir) => {
    let latest = 0;
    const walk = (d) => {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const full = path.join(d, e.name);
        if (e.isDirectory()) walk(full);
        else latest = Math.max(latest, fs.statSync(full).mtimeMs);
      }
    };
    try {
      walk(dir);
    } catch {
      return 0;
    }
    return latest;
  };
  const srcAt = newest(path.join(REPO, "bridge/src"));
  const distAt = newest(path.join(REPO, "bridge/dist"));
  if (distAt === 0 || srcAt > distAt) {
    throw new Error(
      "bridge/dist is missing or OLDER than bridge/src — the manifest comparison below " +
        "would agree with itself on a stale table. Run `npm run build` in bridge/ and " +
        "restart the bridge first.",
    );
  }

  const local = await import(
    pathToFileURL(path.join(REPO, "bridge/dist/compat.js")).href
  ).catch((err) => {
    throw new Error(
      `cannot read this checkout's manifest (bridge/dist/compat.js) — run \`npm run build\` ` +
        `in bridge/ first. Cause: ${err?.message ?? err}`,
    );
  });
  // WHOLE entries, both ways. Comparing capability NAMES alone accepted a stale process
  // whenever a minVersion floor, a supported range or a validated-version list changed
  // without adding or removing a key — which is most version work (raised in review).
  const mine = local.COMPAT_MANIFEST.providers ?? {};
  const served = body?.compat?.providers ?? {};
  for (const provider of new Set([...Object.keys(mine), ...Object.keys(served)])) {
    const a = JSON.stringify(mine[provider] ?? null, replacerSorted);
    const b = JSON.stringify(served[provider] ?? null, replacerSorted);
    if (a !== b) {
      throw new Error(
        `the bridge answering serves a DIFFERENT ${provider} entry than this checkout ` +
          `compiles\n  checkout: ${a}\n  served:   ${b}\n` +
          "rebuild and restart the bridge before capturing",
      );
    }
  }

  const anonymised = anonymise(body, openclaw.instanceName);
  // The OpenClaw target FIRST. Tests select by provider (an index is not a contract), but
  // the file is read by people too, and the subject of the fixture belongs at the top.
  anonymised.targets.sort((a, b) =>
    a.provider === "openclaw" ? -1 : b.provider === "openclaw" ? 1 : 0,
  );
  const source = `bridge ${body.bridgeVersion ?? "?"} / gateway ${openclaw.gatewayVersion}`;
  const module =
    `${header(source, new Date().toISOString().slice(0, 10))}\n` +
    `export const LIVE_CAPABILITIES_BODY = ${JSON.stringify(anonymised, null, 2)} as const;\n`;
  fs.writeFileSync(OUT, module);
  console.log(
    `wrote ${path.relative(REPO, OUT)} — ${Object.keys(manifest).length} manifest ` +
      `capabilities, ${anonymised.targets.length} target(s), gateway ${openclaw.gatewayVersion}`,
  );
}

await main();
